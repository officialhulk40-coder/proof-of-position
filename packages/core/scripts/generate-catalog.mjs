#!/usr/bin/env node
// Generates packages/core/src/tokens/catalog.generated.ts from the resource pack's BSC token registry.
// Model rule (same as contracts/script/data/generate-tokens.mjs): bStock and Ondo are PLAIN; rebasing
// xStocks are XSTOCK; wrapped xStocks ("w…x", e.g. wPOPMTx) are PLAIN.
// Usage (from the repo root): node packages/core/scripts/generate-catalog.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const csvRelative = "docs/resources/2026-10-05-bnb-hack-tokenized-stocks/data/bsc-tokenized-stocks-2026-10-05.csv";
const csvPath = join(here, "..", "..", "..", ...csvRelative.split("/"));
const outPath = join(here, "..", "src", "tokens", "catalog.generated.ts");

const ISSUER = { bStock: "bStocks", Ondo: "Ondo", xStocks: "xStocks" };
const rows = readFileSync(csvPath, "utf8")
  .split(/\r?\n/)
  .filter((line) => line.trim() !== "")
  .slice(1);

const entries = rows.map((line) => {
  const [system, , symbol, ticker, rawAddress, assetType] = line.split(",");
  const issuer = ISSUER[system];
  const address = (rawAddress ?? "").toLowerCase();
  if (!issuer) throw new Error(`unknown system "${system}" for ${symbol}`);
  if (!/^0x[0-9a-f]{40}$/.test(address)) throw new Error(`bad address for ${symbol}: ${rawAddress}`);
  const model = system === "xStocks" && !/^w.+x$/.test(symbol) ? "XSTOCK" : "PLAIN";
  const parsedAssetType = assetType === "1" || assetType === "2" || assetType === "3" ? Number(assetType) : null;
  return `  { address: "${address}", symbol: "${symbol}", ticker: "${ticker}", issuer: "${issuer}", model: "${model}", assetType: ${parsedAssetType} },`;
});

const source = [
  `// GENERATED by packages/core/scripts/generate-catalog.mjs from ${csvRelative} — do not edit.`,
  'import type { TokenInfo } from "./types";',
  "",
  "export const TOKEN_CATALOG: readonly TokenInfo[] = [",
  ...entries,
  "];",
  "",
].join("\n");
writeFileSync(outPath, source);
console.log(`catalog.generated.ts written: ${entries.length} tokens`);
