#!/usr/bin/env node
// Generates packages/core/src/registry/abi.generated.ts from the forge artifact of CallRegistry.
// Usage (from the repo root): node contracts/run-forge.mjs build   then   node packages/core/scripts/generate-registry-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = join(here, "..", "..", "..", "contracts", "out", "CallRegistry.sol", "CallRegistry.json");
const outPath = join(here, "..", "src", "registry", "abi.generated.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  throw new Error(`no ABI in ${artifactPath}`);
}
const required = ["post", "postAsAgent", "recordExit", "close", "getCalls", "statusOf", "callCount", "openCallOf", "tokenModel"];
const names = new Set(artifact.abi.filter((item) => item.type === "function").map((item) => item.name));
const missing = required.filter((name) => !names.has(name));
if (missing.length > 0) {
  throw new Error(`CallRegistry artifact is missing ${missing.join(", ")} — rebuild the final contract first`);
}

const source = [
  "// GENERATED by packages/core/scripts/generate-registry-abi.mjs from contracts/out/CallRegistry.sol/CallRegistry.json — do not edit.",
  "// Regenerate after any CallRegistry change: node contracts/run-forge.mjs build && node packages/core/scripts/generate-registry-abi.mjs",
  `export const CALL_REGISTRY_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
  "",
].join("\n");
writeFileSync(outPath, source);
console.log(`abi.generated.ts written: ${artifact.abi.length} ABI items`);
